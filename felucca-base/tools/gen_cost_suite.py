"""DUELL 1.1 item 105: writes tools/bench_suites/COST-CAL.txt, the bench suite that measures what every engine and every switch costs on the unit, so the NOTES budget's cost table
comes from measurements. tools/cost_fit.py reads the run and writes the table, the report and a patch for budget.c.

  python3 tools/gen_cost_suite.py                 the full suite -> tools/bench_suites/COST-CAL.txt        (about 1 hour 5 minutes on the unit)
  python3 tools/gen_cost_suite.py --quick         a short one   -> tools/bench_suites/COST-CAL-QUICK.txt  (about 10 minutes: one engine's features, the engines at 1, 4, 8 keys, no repeats)
  python3 tools/gen_cost_suite.py --cal1          the short ONE-CORE set -> tools/bench_suites/COST-CAL1.txt (about 15 minutes; item 112: every test `tune core1 off`, needs BENCHV3 or newer)
  python3 tools/gen_cost_suite.py --no-sounds     the full suite without the survey of every factory sound (about 12 minutes less)
  python3 tools/gen_cost_suite.py --list          the tests and the minutes of each section, nothing written

What a test is (tools/cost_defs.py holds all of it): both parts the same sound, LAYER (or DUEL / STEREO for the global rows), the NOTES budget held open, a chord held 2.4 s, the CPU measured
from 0.9 s to 2.4 s. The scene is the engine's dearest factory sound CLEANED (multimode filter bypassed, no TWIN, SUB, matrix, MORPH, INSERT, SAT, EQ, DUCK, arp, sends), MODULES SENDS off,
no master stage, KEY SENSE off. Then:
  B  every engine, that baseline with 1, 2, 4, 8, 12 keys, on one core (`tune core1 off`, item 112: BENCHV3 and later; `tune slack 400000` stopped being one-core with DUELL 1.1 item 90, HANDOFF_V2 item 110) and on two. Counts the unit cannot carry (their predicted load is over
     70 %) are left out; the unit reports the voices it really sounds (vox), so a count above the pool's cap is a check, not a data point
  F  ANALOG, one core: each feature ALONE from the baseline (MULTI 12 / 24 dB, BP mode, KEY TRK, MORPH still / moving, TWIN LP / BP / LADDER / COMB / DRIVE / PARALLEL / modulation, SUB x4,
     UNISON, matrix slot / LFO / CYCLE) with 1 and 3 keys (a per-voice cost shows as a slope), each part stage (INSERT x10, SAT, EQ 1-3, DUCK) with 2 and 6 keys (a fixed cost must not change),
     and the BYPASS of each (does it save the cost?)
  X  the per-voice features on every other engine, 2 keys
  G  the global side, 2 keys, against SENDS OFF: idle mix (no keys), SENDS ON with nothing fed, CHORUS, DELAY x4, REVERB x6, SHIM variants, send level 0 checks, the BYPASS of each bus,
     COMP, WIDTH, BASS MONO, KEY VELOCITY, a muted part; LAYER and DUEL (and STEREO for the bus row)
  S  every factory sound of every engine (cleaned, filter bypassed), 4 keys: the spread behind one engine row
  H  13 held-out combinations (several things on at once) that the fit never sees: cost_fit.py validate predicts them
Baseline and features run twice (`repeat 2`: the spread), the survey once. A test takes about 5 to 6 s.
Needs the developer bench build with the COST-CAL words (firmware/src/bench.c: sound, mods, bypass, master, morph, keysense, set on ids 128..155).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import cost_defs as D  # noqa: E402


def main():
    quick = "--quick" in sys.argv
    cal1 = "--cal1" in sys.argv
    plan = D.build_plan(quick, sounds="--no-sounds" not in sys.argv, cal1=cal1)
    name = "COST-CAL1" if cal1 else "COST-CAL-QUICK" if quick else "COST-CAL"
    secs = {}
    for t in plan:
        secs[t["sec"]] = secs.get(t["sec"], 0.0) + D.seconds_of(t)
    total = sum(secs.values())
    runs = sum(t["repeat"] for t in plan)
    if "--list" in sys.argv:
        for t in plan:
            print(f"{t['name']:34s} x{t['repeat']}  {t['text']}")
    out = [f"# {name} (generated by tools/gen_cost_suite.py, DUELL 1.1 item 105): what every engine and every switch costs on the unit. Read the run with tools/cost_fit.py.",
           "# Both parts the same cleaned sound, the NOTES budget held open. B baseline per engine, F features alone (ANALOG), X the same on the other engines, G global side, S factory sounds, H held out."
           + ("  COST-CAL1: ONE core only, every test `tune core1 off` (core 1 treated as down, the one-core budget): needs a BENCHV3 or newer bench build." if cal1 else ""),
           f"suite {name}", "diag", ""]
    for t in plan:
        out += D.test_lines(t)
    path = os.path.join(HERE, "bench_suites", name + ".txt")
    if "--list" not in sys.argv:
        open(path, "w").write("\n".join(out) + "\n")
    print(f"gen_cost_suite: {len(plan)} tests, {runs} runs -> {path if '--list' not in sys.argv else '(not written)'}")
    print("  minutes by section (estimate, 5 to 6 s a run): " + ", ".join(f"{k} {v / 60:.1f}" for k, v in sorted(secs.items())) + f";  total about {total / 60:.0f} minutes")
    # the planned load of the heaviest tests, from the 1.1 table: a run over about 85 % would be clipped and left out of the fit
    heavy = sorted(((D.predict_avg(t["cfg"], D.HINT), t["name"]) for t in plan), reverse=True)[:3]
    print("  heaviest planned loads (1.1 table): " + ", ".join(f"{n} {p:.0f} %" for p, n in heavy))


if __name__ == "__main__":
    main()
