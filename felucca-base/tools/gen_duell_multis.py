"""DUELL factory multis: tools/factory_multis/M01.bin..M16.bin (raw multi records, firmware/src/multi.c format) -> build/gen/duell_multis.h.

    tools/gen_duell_multis.py build/gen/duell_multis.h                 (tools/build.py generate(), DUELL/gen_only.py)
    DUELL_TEST_MODE=1 tools/gen_duell_multis.py ...  (or --test-mode)   the same sixteen multis; the header says DF_TEST_MULTIS 1

The records and what each must hold come from tools/factory_multis.py (MULTIS: the slot, the name, the two sounds, the MODE, the
split; `tools/factory_multis.py build` makes them). Checked here as there: version 7 (multi.c MU_VER, the only one it loads), the
expected name (ASCII, at most 12), each part's engine + factory index naming the intended sound of tools/duell_sounds.py (a changed
sound list stops the build), the MODE byte, the reverb LOW CUT at its default, at most MU_REC_MAX (1916) bytes.
DUELL 0.2.23: all sixteen slots hold a factory multi in every build, M16 STRESS TEST included (a CPU test the owner plays on the
unit; free to overwrite). The CPU TEST multis of developer builds (M13..M16 until 0.2.22) are test scenes now (tests/scenes/,
tests/scenes.h), not factory multis, so the release and the test mode hold the same records; DF_TEST_MULTIS only says which switch
the header was made with (multi.c checks it against DUELL_TEST_MODE).
Output: DF_N, DF_SLOT[] (the slot of each), DM_LEN[], DM_REC[] (one concatenated const array) and DM_AT[] (offsets).
"""
import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def die(msg):
    sys.exit("gen_duell_multis: " + msg)


def main(argv):
    args = [a for a in argv[1:] if a != "--test-mode"]
    test_mode = len(args) != len(argv) - 1 or os.environ.get("DUELL_TEST_MODE") == "1"
    if len(args) != 1:
        die("usage: gen_duell_multis.py [--test-mode] OUT.h")
    out = Path(args[0])
    spec = importlib.util.spec_from_file_location("factory_multis", ROOT / "tools" / "factory_multis.py")
    fm = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fm)
    snd = fm.sounds()
    fm.resolve(snd)
    by_idx = {(s["engine"], s["idx"]): s["name"] for s in snd}
    P = fm.p_ids()
    multis = sorted(fm.MULTIS, key=lambda m: m["slot"])
    recs = []
    for m in multis:
        f = fm.DIR / ("M%02d.bin" % m["slot"])
        if not f.exists():
            die("%s missing (tools/factory_multis.py build)" % f.name)
        b = f.read_bytes()
        err = fm.check_record(m, b, by_idx, P)
        if err:
            die("; ".join(err))
        recs.append(b)
    lines = ["/* generated by tools/gen_duell_multis.py from the M*.bin files in tools/factory_multis: do not edit */",
             "#define DF_TEST_MULTIS %d" % (1 if test_mode else 0),
             "#define DF_N %du" % len(recs),
             "static const uint8_t DF_SLOT[DF_N] = {%s};" % ", ".join(str(m["slot"] - 1) for m in multis),
             "static const uint16_t DM_LEN[DF_N] = {%s};" % ", ".join(str(len(b)) for b in recs),
             "static const uint16_t DM_AT[DF_N] = {%s};" % ", ".join(str(sum(len(x) for x in recs[:k])) for k in range(len(recs)))]
    flat = b"".join(recs)
    lines.append("static const uint8_t DM_REC[%d] = {" % len(flat))
    for i in range(0, len(flat), 24):
        lines.append("    " + ", ".join("%d" % c for c in flat[i:i + 24]) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print("duell_multis.h: %d factory multis, %d bytes%s" % (len(recs), len(flat), " (test mode)" if test_mode else ""))


if __name__ == "__main__":
    main(sys.argv)
