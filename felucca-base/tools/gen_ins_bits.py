#!/usr/bin/env python3
"""CRUSH BITS knob curve (0.2.14): writes firmware/src/ins_bits.h (committed; rerun only if the curve changes).
Usage: python3 tools/gen_ins_bits.py [out.h]
The knob's 128 detents (INS A 0..127) cover 1 .. 16 bits with every detent a different depth (the quantiser step is
fractional, Q8). Whole bit counts sit on knots (KNOT[b-1], the detent of b bits): 1 bit at 0, 16 bits at 126 (and 127), the gaps
between knots shrinking from about 15 detents a bit at the bottom to 8 at 10 bits (geometric), then 3 a bit for 11 .. 16: the
quantiser error of 10 bits and more is under -60 dB of a loud voice, no click there changes the sound audibly whatever the map, so
those six bits take the last 18 detents and every detent below changes it. Between knots the depth is linear in bits (the step 2^(16 - b))."""
import sys, os, math
R = 0.93  # gap ratio per bit for 1 .. 10 bits; the gaps sum to 108
gaps = [R ** k for k in range(9)]
sc = 108.0 / sum(gaps)
cum, acc = [0], 0.0
for g in gaps:
    acc += g * sc
    cum.append(int(round(acc)))
knot = cum + [111, 114, 117, 120, 123, 126]  # 10 bits at 108, then 11 .. 16 three detents apart
assert len(knot) == 16 and knot[15] == 126 and all(b > a for a, b in zip(knot, knot[1:])), knot
bits = []
for p in range(128):
    if p >= 126:
        bits.append(16.0)
        continue
    k = max(i for i in range(15) if knot[i] <= p)
    bits.append(1 + k + (p - knot[k]) / (knot[k + 1] - knot[k]))
step = [int(round(256 * 2 ** (16 - b))) for b in bits]
step[126] = step[127] = 256
show = []
for p in range(128):
    s = int(math.floor(bits[p] + 0.5))
    if p < 126 and s > 15:
        s = 15  # 16 is shown only where the quantiser is clean
    show.append(s)
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "../firmware/src/ins_bits.h")
with open(out, "w") as f:
    f.write("/* SPDX-License-Identifier: GPL-3.0-only */\n/* GENERATED by tools/gen_ins_bits.py: CRUSH BITS curve (INSERT A, fx.c ins_bits_step, params.c N_IBITS). Do not edit. */\n#ifndef INS_BITS_H\n#define INS_BITS_H\n")
    f.write("/* the detent of 1 .. 16 bits (whole bits sit exactly here) */\n")
    f.write("static const uint8_t INS_BITS_KNOT[16] = {" + ", ".join(map(str, knot)) + "};\n")
    f.write("/* the quantiser step at each detent, Q8 (256 = 1: 16 bits, clean; 2^23 = 1 bit) */\n")
    f.write("static const uint32_t INS_BITS_STEP[128] = {\n" + ",\n".join("    " + ", ".join(map(str, step[i:i + 8])) for i in range(0, 128, 8)) + "};\n")
    f.write("/* the whole bit count each detent shows (nearest; 16 only where the step is 1) */\n")
    f.write("static const char *const N_IBITS[] = {\n" + ",\n".join("    " + ", ".join('"%d"' % s for s in show[i:i + 16]) for i in range(0, 128, 16)) + ", 0};\n")
    f.write("#endif\n")
print("knots", knot)
print("show", show)
print("minrel step change", min(abs(step[i + 1] - step[i]) / step[i] for i in range(125)))
