"""DUELL 1.0: the data of the update loader's screen (firmware/loader/ldr_screen.c) -> firmware/loader/ldr_screen_data.h (committed; the loader is built
in parallel with generate(), so its data is a source file, remade only when this script or its inputs change).

    tools/gen_loader_screen.py [OUT.h]        (needs Pillow: DUELL/.venv/bin/python; build/gen/ui_palettes.h and splash_logo.h from DUELL/gen_only.py)

Everything is the device's own: the VIOLET palette (bg, text, part colours c0 / c2, raise), the DUELL word of the splash lockup (build/gen/splash_logo.h,
rows 0..33, the 4-bit coverage run list as it is), the splash's sine table (a quarter wave; the loader draws the splash's morphing wave lines), and the UI's typeface
Inter Tight (assets/fonts/InterTight[wght].ttf, weight 500, 15 px, the M face of tools/gen_aa_font.py): WRITING and DO NOT SWITCH OFF as two whole bitmaps (4-bit alpha,
two pixels a byte, row after row), the digits and % as glyphs for the percent. The picture it makes is release_drafts/LOADER_SCREEN_DESIGN.png (tools/loader_screen_design.py)."""
import math
import re
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = str(ROOT / "assets" / "fonts" / "InterTight[wght].ttf")


def pal():
    t = (ROOT / "build/gen/ui_palettes.h").read_text()
    m = re.search(r'\{"VIOLET", \{(0x\w+), 0x\w+\}, 0x\w+, \{(0x\w+), (0x\w+)\}, (0x\w+), (0x\w+), \{(0x\w+), (0x\w+)\}, \{(0x\w+), (0x\w+)\}, (0x\w+), \{(0x\w+), (0x\w+), (0x\w+)', t)
    v = [int(x, 16) for x in m.groups()]
    return dict(bg=v[0], text=v[3], raise_=v[7], c0=v[10], c2=v[12])


def logo():
    t = (ROOT / "build/gen/splash_logo.h").read_text()
    w = int(re.search(r"SPL_LOGO_W (\d+)", t).group(1))
    body = re.search(r"SPL_LOGO\[\d+\] = \{(.*?)\};", t, re.S).group(1)
    runs = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", body)]
    out, p, lim = [], 0, w * 34                      # the first 34 rows
    for b in runs:
        n = (b & 15) + 1
        take = min(n, lim - p)
        if take > 0:
            out.append((b & 0xF0) | (take - 1))
        p += n
        if p >= lim:
            break
    return w, 34, out


def font():
    f = ImageFont.truetype(FONT, 15)
    f.set_variation_by_axes([500])
    return f


def bitmap(f, s, pad=3):
    """the ink of s (drawn like the design picture: pen at the left, ascender line on top) as 4-bit alpha: (w, h, x offset of the ink from the pen, y offset from the top, nibbles)"""
    im = Image.new("L", (400, 40), 0)
    ImageDraw.Draw(im).text((pad, pad), s, font=f, fill=255)
    bb = im.getbbox()
    c = im.crop(bb)
    w, h = c.size
    nib = [(c.getpixel((x, y)) + 8) * 15 // 255 for y in range(h) for x in range(w)]
    nib = [min(15, v) for v in nib]
    if len(nib) & 1:
        nib.append(0)
    data = [(nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2)]
    return w, h, bb[0] - pad, bb[1] - pad, data


def arr(name, vals, per=16, typ="uint8_t"):
    s = "static const %s %s[%d] = {\n" % (typ, name, len(vals))
    for i in range(0, len(vals), per):
        s += "    " + ",".join(str(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "firmware/loader/ldr_screen_data.h"
    P = pal()
    lw, lh, lruns = logo()
    f = font()
    asc = f.getmetrics()[0]
    q = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(257)]
    full = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
    def sq(i):
        i &= 1023
        return q[i] if i <= 256 else q[512 - i] if i <= 512 else -q[i - 512] if i <= 768 else -q[1024 - i]
    assert all(sq(i) == full[i] for i in range(1024)), "the quarter-wave table does not rebuild the splash's"
    h = ["/* generated by tools/gen_loader_screen.py: do not edit (SPDX-License-Identifier: GPL-3.0-only) */",
         "/* the update loader's screen: the VIOLET palette, the splash's sine quarter wave, the DUELL word of the splash lockup, Inter Tight 15 px at weight 500 */"]
    for k, v in P.items():
        h.append("#define LS_%s 0x%04xu" % (k.upper(), v))
    h.append("#define LS_LOGO_W %d" % lw)
    h.append("#define LS_LOGO_H %d" % lh)
    s = arr("LS_SINE_Q", q, 12, "int16_t") + arr("LS_LOGO", lruns, 24)
    glyphs = []
    for name, text in (("WRITING", "WRITING"), ("DONOT", "DO NOT SWITCH OFF")):
        w, hh, bx, by, data = bitmap(f, text)
        h.append("#define LS_%s_W %d\n#define LS_%s_H %d\n#define LS_%s_BX %d\n#define LS_%s_BY %d" % (name, w, name, hh, name, bx, name, by))
        s += arr("LS_%s" % name, data, 24)
    digits = "0123456789%"
    offs, tab, blob = [], [], []
    for ch in digits:
        w, hh, bx, by, data = bitmap(f, ch)
        adv = round(f.getlength(ch))
        tab += [len(blob), w, hh, bx & 255, by & 255, adv]
        blob += data
    assert max(tab[0::6]) < 65536
    s = s.replace("", "")
    h.append("#define LS_NG 11\n#define LS_GW 6          /* per glyph: offset (low, high), w, h, x offset, y offset, advance: see ldr_screen.c */")
    tab2 = []
    for i in range(11):
        o = tab[i * 6]
        tab2 += [o & 255, o >> 8, tab[i * 6 + 1], tab[i * 6 + 2], tab[i * 6 + 3], tab[i * 6 + 4], tab[i * 6 + 5]]
    h[-1] = "#define LS_NG 11"
    s += arr("LS_GLYPH", tab2, 14) + arr("LS_GDATA", blob, 24)
    out.write_text("\n".join(h) + "\n" + s)
    print("wrote", out, out.stat().st_size, "B of source; logo run list", len(lruns), "B")


main()
