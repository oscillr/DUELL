"""Write the version header from the single source of truth, the VERSION file at the DUELL root.

  tools/gen_version.py build/gen/duell_version.h

DUELL_VERSION      "0.2.1"
DUELL_VERSION_STR  "DUELL 0.2.1 beta" (a 0.x.y version) or "DUELL 1.0" (1.0 and later: no beta)   (what the device and the emulator page show)
"""
import re
import sys
from pathlib import Path

vfile = Path(__file__).resolve().parents[2] / "VERSION"
ver = vfile.read_text().strip() if vfile.exists() else ""
if not re.fullmatch(r"0\.\d+\.\d+|[1-9]\d*\.\d+", ver):
    sys.exit(f"gen_version: {vfile} must hold 0.MINOR.BUILD (e.g. 0.2.1) or MAJOR.MINOR (1.0), found {ver!r}")
beta = " beta" if ver.startswith("0.") else ""
Path(sys.argv[1]).write_text(
    "/* generated by tools/gen_version.py from the VERSION file; do not edit */\n"
    f'#define DUELL_VERSION "{ver}"\n#define DUELL_VERSION_STR "DUELL {ver}{beta}"\n')
