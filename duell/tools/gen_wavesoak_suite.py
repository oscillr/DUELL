"""WAVE-SOAK (DUELL 1.2, 2026-11-08; replaces the BENCHV8 version of 2026-11-02, never run): writes tools/bench_suites/WAVE-SOAK.txt, the soak that hunts the WAVE chord crackle
(owner, 2026-11-02: WAVE, 4-voice chords, the unit showing a 4-voice limit, 2-3 crackles in a few minutes, no pattern, also without page changes; owner 2026-11-08: "make a detailed test").

The product's own limits stay ON: the voice budget as the screen shows it (no `budget OPEN`), the protection as it ships. STEREO, part 1 plays alone.
Five sounds: three factory WAVE patches as they are (#60 DIGITAL PAD, #61 EVOLVING PAD, #116 FROZEN AIR, the one with TWIN) and the everything-on WAVE test
patch of MAX-VOICES-PART (WAVE DEAR with every feature on and moving, the same words) at MORPH A and at MORPH B.
Three chords that share no pitch: P = C3 E3 G3 C4 (4 notes), Q = G2 B2 D3 F3 (4 notes, a G7), R = D2 A2 F#3 A3 D4 F#4 (6 notes: above the screen's number on the heavy
sounds, so the voice stealing runs too). Three ways to play them, each over and over for SECS seconds (default 85; --secs N overrides):
  GAP      chord, release, 0.5 s gap, next chord
  RELEASE  the next chord 0.1 s after the release (the one before still in its release tail)
  LEGATO   the next chord 0.05 s BEFORE the one before is released (overlap)
15 cells x 85 s: about 23 minutes with the set-up. Run with --record (owner rule: every bench run records; the audio is checked for clicks and gaps) and read
late_latch.csv (the first late halves of every cell) and soak_checks.csv.

  python3 tools/gen_wavesoak_suite.py [--secs N]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_maxvoice_suite import GLOBALS, moving  # noqa: E402  (the everything-on words, the same as MAX-VOICES-PART)

HERE = os.path.dirname(os.path.abspath(__file__))
PATCHES = [60, 61, 116]
P = ["C3", "E3", "G3", "C4"]
Q = ["G2", "B2", "D3", "F3"]
R = ["D2", "A2", "F#3", "A3", "D4", "F#4"]
# name: (period, [(time, chord, length)], text)
PATTERNS = {
    "GAP": (10.5, [(0.0, P, 3.0), (3.5, Q, 3.0), (7.0, R, 3.0)], "chord, release, 0.5 s gap, next chord"),
    "RELEASE": (9.3, [(0.0, P, 3.0), (3.1, Q, 3.0), (6.2, R, 3.0)], "next chord 0.1 s after the release"),
    "LEGATO": (9.0, [(0.0, P, 3.05), (3.0, Q, 3.05), (6.0, R, 3.05)], "next chord 0.05 s before the release (overlap)"),
}


def main():
    secs = 85
    if "--secs" in sys.argv:
        secs = int(sys.argv[sys.argv.index("--secs") + 1])
    bank = {p["number"]: p for p in json.load(open(os.path.join(HERE, "factory_bank.duell-patches.json")))["patches"]}
    sounds = []
    for num in PATCHES:
        p = bank[num]
        assert p["engine"].upper() == "WAVE"
        sounds.append((f"WS{num}", f"WAVE #{num:02d} {p['name']} as it is", [f'load patch 1 #{num:02d} "{p["name"]}"']))
    for end, fader in (("A", 0), ("B", 127)):
        sounds.append((f"WSDEAR{end}", f"WAVE everything on and moving (MAX-VOICES-PART's), MORPH {end}",
                       ["sound 1 WAVE DEAR", "sound 2 WAVE DEAR", *GLOBALS, *moving(1), *moving(2), f"morph 1 FADER {fader}", f"morph 2 FADER {fader}"]))
    n = len(sounds) * len(PATTERNS)
    out = ["# WAVE-SOAK (generated by tools/gen_wavesoak_suite.py, DUELL 1.2, 2026-11-08): the WAVE chord crackle hunt, the product's limits on. STEREO, part 1 alone,",
           f"# 5 WAVE sounds x 3 ways to play, each {secs} s ({n} cells, about {n * (secs + 8) // 60} minutes). Chords: P C3 E3 G3 C4, Q G2 B2 D3 F3, R D2 A2 F#3 A3 D4 F#4.",
           "suite WAVE-SOAK", "diag", ""]
    for tag, text, setup in sounds:
        for pat, (period, evs, ptext) in PATTERNS.items():
            cyc = f"{tag}-{pat}"
            out.append(f"cycle {cyc} period {period}")
            for t, ch, ln in evs:
                for nn in ch:
                    out.append(f"at {t:.2f}  note {nn} vel 90 len {ln}")
            out.append("end")
            out.append("")
            out.append(f"test {tag}_{pat}  {text}, STEREO, part 1 alone, {ptext}, {secs} s")
            out.append("mode STEREO")
            out.extend(setup)
            out.append(f"soak {secs} repeat {cyc}")
            out.append("check 60")
            out.append("tail 3")
            out.append("expect report")
            out.append("")
    path = os.path.join(HERE, "bench_suites", "WAVE-SOAK.txt")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"gen_wavesoak_suite: WAVE-SOAK: {n} tests x {secs} s -> {path}")


if __name__ == "__main__":
    main()
