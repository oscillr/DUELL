"""DUELL 1.1 item 90: writes tools/bench_suites/POLY-MAX.txt, the bench suite that finds how many notes really play on the unit.

For every engine (its first factory patch, on BOTH parts), three filter settings (MULTI off = bypassed, MULTI 12 dB, MULTI 12 dB + TWIN LP), LAYER, the NOTES budget held
open (`budget OPEN`: every voice the part has sounds), 1 to 8 keys held for 6 s, once on two cores (`tune core1 on`) and once on one core (`tune core1 off`, BENCHV3 or newer: core 1 treated as down,
core 0 plays part 2 itself, the one-core budget; `tune slack 400000` is no longer one-core since item 90). Two suites: POLY-MAX (budget OPEN, the capacity) and POLY-MAX-BUDGET
(the same cases with `budget ON`, the NOTES budget as the owner plays it, to verify its caps). tools/polymax_report.py then reads results.csv and writes polymax.csv: per engine, filter and cores the most
keys with no missed half and a peak under the limit.

  python3 tools/gen_polymax_suite.py            [--quick]   (--quick: 1, 2, 4, 6, 8 keys only)

DUELL 1.1 item 142 (HANDOFF_V2 items 139, 140): POLY-MAX-BUDGET stays as it is (the realistic case: the loaded patch with its MORPH and its own matrix, SUB, SAT ..; the host
predicts its numbers: tests/poly_limits_test.c "state S"). A third suite POLY-MAX-BUDGET-A tests STATE A on the unit, the state of the host's caps tables: ANALOG, TRIO and WAVE
(their first factory patch, both parts), MOFF / M12 / M12TW, `budget ON`, two cores 4 to 8 keys and one core 2 to 4 keys, each test twice (`repeat 2`). On top of POLY-MAX-BUDGET's
`set` values it clears the 8 matrix slots (ids 49 .. 72), the extension values (ids 128 .. 152: SUB LEVEL 134, the TWIN's ROUTE / KEY TRK 2 / ENV 2 / LFO 1 / LFO 2 ..; LINK 129
stays, and the two LFO LEVELs 153 / 154 and 155 are not touched, as tests/poly_limits_test.c clean() leaves LINK and the levels), DRIVE 2 (26), SAT (33), the EQ gains (8, 88, 103) and DUCK (107), then `morph 1 OFF` /
`morph 2 OFF` (no morph list). INSERT and the sends stay the patch's (all three: INSERT OFF). Read: tools/polymax_report.py; the run-wide counters (bench_run.py --onset)
show a note-on burst, which the CPU window 1.0 .. 6.0 s does not.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ENGINES = ["ANALOG", "PHASE", "WAVE", "WHEEL", "VOICE", "FM6", "PHYS", "TRIO", "NOISE", "LOFI"]
# parameter ids (core.h; the bench's `set PART ID VALUE` takes the id): P_FREEA 45 (MULTI CUT, 82 = open), P_FREEC 47 (MODE, 0 = LP), P_FREED 48 (SLOPE), P_KTRK 27,
# P_TWTYPE 43 (0 OFF, 1 LP), P_CUT2 106, P_VOICE 37 (POLY = 0), P_AMODE 17 (arp off), the cutoff depths P_LD_FLT 14, P_ED_FLT 5, P_E2FLT 114, P_L2FLT 117,
# P_CHRD 81 (chord keys, 0 = OFF: factory patches such as ANALOG #01 BEHIVE carry a chord, which would play 3 notes per key)
CLEAN = [("81", 0), ("37", 0), ("17", 0), ("27", 0), ("14", 0), ("5", 0), ("114", 0), ("117", 0)]
VARIANTS = {
    "MOFF": [("45", 82), ("47", 0), ("48", 1), ("43", 0)],
    "M12": [("45", 50), ("47", 0), ("48", 1), ("43", 0)],
    "M12TW": [("45", 50), ("47", 0), ("48", 1), ("43", 1), ("106", 10)],
}
NOTES = ["C3", "E3", "G3", "B3", "D4", "F4", "A4", "C5"]
# item 142: STATE A on top of CLEAN (see the docstring): the matrix slots, the extension values but LINK / LFO 1 LEVEL / LFO 2 LEVEL, DRIVE 2, SAT, EQ, DUCK
CLEAN_A = ([(str(i), 0) for i in range(49, 73)] + [(str(128 + i), 0) for i in range(25) if i != 1] +   # (128 .. 152: X27 / 155, the KEY OFFSET, is left alone: it costs nothing and item 141 removes it)
           [("26", 0), ("33", 0), ("8", 0), ("88", 0), ("103", 0), ("107", 0)])
A_ENGINES = ["ANALOG", "TRIO", "WAVE"]
# the host's caps of exactly this state (budget.c at BUDGET_LIMIT 84, margin 1.00, KEY SENSE +57; HANDOFF_V2 item 142's probe): one core / two cores a part
A_CAPS = {("ANALOG", "MOFF"): (8, 8), ("ANALOG", "M12"): (4, 8), ("ANALOG", "M12TW"): (3, 7), ("TRIO", "MOFF"): (8, 8), ("TRIO", "M12"): (4, 8), ("TRIO", "M12TW"): (3, 7),
          ("WAVE", "MOFF"): (7, 8), ("WAVE", "M12"): (4, 8), ("WAVE", "M12TW"): (3, 7)}


def main():
    quick = "--quick" in sys.argv
    for name, budget in (("POLY-MAX", "OPEN"), ("POLY-MAX-BUDGET", "ON")):
        build(name, budget, quick)
    build_a("POLY-MAX-BUDGET-A")


def build_a(name):
    """item 142: state A on the unit (two cores 4 .. 8 keys, one core 2 .. 4 keys, 2 repeats)"""
    bank = json.load(open(os.path.join(HERE, "factory_bank.duell-patches.json")))["patches"]
    first = {}
    for p in bank:
        first.setdefault(p["engine"].upper(), p)
    out = [f"# {name} (generated by tools/gen_polymax_suite.py, DUELL 1.1 item 142): STATE A on the unit, the state of the host's caps tables (tests/poly_limits_test.c state A).",
           "# LAYER, both parts the engine's first factory patch with POLY-MAX-BUDGET's set values plus: no matrix slot, no SUB / TWIN extension values, no DRIVE 2, SAT, EQ, DUCK; MORPH off.",
           "# The NOTES budget ON. Host caps of this state at BUDGET_LIMIT 84 (one core / two cores a part; the result's notes1 / notes2 must show them):",
           "#   " + "   ".join(f"{e} {v} {A_CAPS[(e, v)][0]}/{A_CAPS[(e, v)][1]}" for e in A_ENGINES for v in VARIANTS),
           "# Pass (item 139): 0 silent, 0 pauses, 0 missed halves over the WHOLE run (bench_run.py --onset: the note-on burst is outside the CPU window), shed 0 and LIGHT FX 0, peak <= 90 %.",
           f"suite {name}", ""]
    n = 0
    for e in A_ENGINES:
        p = first[e]
        for v, sets in VARIANTS.items():
            for cores, counts in (("2C", range(4, 9)), ("1C", range(2, 5))):
                for k in counts:
                    out.append(f"test POLYA_{e}_{v}_{cores}_N{k}  {e} #{p['number']:02d} {p['name']}, {v}, state A, {'two cores' if cores == '2C' else 'one core'}, {k} keys "
                               f"(host caps {A_CAPS[(e, v)][0]}/{A_CAPS[(e, v)][1]})")
                    out.append("repeat 2")
                    out.append("mode LAYER")
                    for part in (1, 2):
                        out.append(f'load patch {part} #{p["number"]:02d} "{p["name"]}"')
                        for pid, val in CLEAN + CLEAN_A + sets:
                            out.append(f"set {part} {pid} {val}")
                    out.append("morph 1 OFF")
                    out.append("morph 2 OFF")
                    out.append("budget ON")
                    out.append("tune core1 off" if cores == "1C" else "tune core1 on")
                    out.append("at 0.0  chord " + " ".join(NOTES[:k]) + " vel 100")
                    out.append("at 6.0  release")
                    out.append("tail 1")
                    out.append("measure 1.0 6.0")
                    out.append("expect report")
                    out.append("")
                    n += 1
    path = os.path.join(HERE, "bench_suites", f"{name}.txt")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"gen_polymax_suite: {name}: {n} tests x 2 repeats -> {path} (about {n * 2 * 10 // 60} minutes)")


def build(name, budget, quick):
    bank = json.load(open(os.path.join(HERE, "factory_bank.duell-patches.json")))["patches"]
    first = {}
    for p in bank:
        first.setdefault(p["engine"].upper(), p)
    counts = [1, 2, 4, 6, 8] if quick else list(range(1, 9))
    out = [f"# {name} (generated by tools/gen_polymax_suite.py, DUELL 1.1 item 90): how many keys play before the CPU runs out, per engine, filter and cores.",
           f"# LAYER, both parts the engine's first factory patch, the NOTES budget {'held open' if budget == 'OPEN' else 'ON (as the owner plays it)'}. Read the result with tools/polymax_report.py.", f"suite {name}", "diag", ""]
    n = 0
    for e in ENGINES:
        p = first.get(e) or first.get("VOICE" if e == "VOICE" else e)
        if not p:
            continue
        for v, sets in VARIANTS.items():
            for cores in ("2C", "1C"):
                for k in counts:
                    out.append(f"test POLY_{e}_{v}_{cores}_N{k}  {e} #{p['number']:02d} {p['name']}, {v}, {'two cores' if cores == '2C' else 'one core'}, {k} keys")
                    out.append("mode LAYER")
                    for part in (1, 2):
                        out.append(f'load patch {part} #{p["number"]:02d} "{p["name"]}"')
                        for pid, val in CLEAN + sets:
                            out.append(f"set {part} {pid} {val}")
                    out.append(f"budget {budget}")
                    out.append("tune core1 off" if cores == "1C" else "tune core1 on")
                    out.append("at 0.0  chord " + " ".join(NOTES[:k]) + " vel 100")
                    out.append("at 6.0  release")
                    out.append("tail 1")
                    out.append("measure 1.0 6.0")
                    out.append("expect report")
                    out.append("")
                    n += 1
    path = os.path.join(HERE, "bench_suites", f"{name}.txt")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"gen_polymax_suite: {name}: {n} tests -> {path} (about {n * 9 // 60} minutes)")


if __name__ == "__main__":
    main()
