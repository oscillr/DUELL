"""OCTOPUS (owner, 2026-11-08): writes tools/bench_suites/OCTOPUS.txt. "Adjust all the sliders in every direction like crazy, like an octopus would twist and turn
every knob constantly, to make sure nothing makes a crackle. The user shouldn't be able to make a crackle no matter what kind of music or what kind of patch."

The product's own limits stay ON (the voice number as the screen shows it, the protection as it ships). STEREO, part 1 plays. Every engine (WAVE twice), each started
from one of its patches; then every knob that has a MIDI CC (the 70 lines of the default map: engine knobs, MULTI and TWIN filters, SUB, envelopes, LFOs, CYCLE, sends,
the global effects, MORPH fader, ROLL, AMOUNT) is swept while chords play: CCOUNT sweeps in every cycle, each a random knob from a random value to another over 0.3 to 3 s,
overlapping, so many knobs move at once. Chords (no shared pitch): C3 E3 G3 C4, G2 B2 D3 F3, D2 A2 F#3 A3 D4 F#4, each started 0.05 s before the one before ends.
Random but repeatable (a fixed seed per test). Run with --record and read late_latch.csv, the missed halves and the recorded clicks.

  python3 tools/gen_octopus_suite.py [--secs N]
"""
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAPCSV = os.path.join(HERE, "..", "..", "..", "public repo", "docs", "MIDI_MAP_DEFAULTS.csv")
ENGINES = ["WAVE", "WAVE", "ANALOG", "LOFI", "NOISE", "PHASE", "TRIO", "FM6", "PHYS", "WHEEL", "VOICE"]
CHORDS = [(0.0, ["C3", "E3", "G3", "C4"]), (3.0, ["G2", "B2", "D3", "F3"]), (6.0, ["D2", "A2", "F#3", "A3", "D4", "F#4"])]
PERIOD, LEN, CCOUNT = 9.0, 3.05, 40
MORPH_CC, ROLL_CC = 70, 102
# Owner, 2026-11-08: a roll may only change the end you do not hear: End A is rolled only with the fader fully at B, End B only with it fully at A.
# So the fader and ROLL are not swept at random: each cycle the fader goes to A, End B is rolled, the fader goes to B, End A is rolled.
MORPH_ROLL = ["at 0.00  knob 70 127 0 over 1.00", "at 1.50  knob 102 64 127 over 0.30", "at 2.00  knob 102 127 64 over 0.30",
              "at 3.00  knob 70 0 127 over 1.50", "at 5.00  knob 102 64 0 over 0.30", "at 5.50  knob 102 0 64 over 0.30"]


def knobs():
    out = []
    for ln in open(MAPCSV):
        if ln.startswith("#") or ln.startswith("cc,"):
            continue
        cc, target, rule, tag = ln.strip().split(",")[:4]
        if tag == "SHIPPED" and target != "REMOVED" and int(cc) not in (MORPH_CC, ROLL_CC):
            out.append(int(cc))
    return out


def main():
    secs = 70
    if "--secs" in sys.argv:
        secs = int(sys.argv[sys.argv.index("--secs") + 1])
    ccs = knobs()
    bank = json.load(open(os.path.join(HERE, "factory_bank.duell-patches.json")))["patches"]
    used = {}
    out = ["# OCTOPUS (generated by tools/gen_octopus_suite.py, 2026-11-08): every knob with a MIDI CC swept at random while chords play, every engine, the product's limits on.",
           f"# {len(ENGINES)} tests x {secs} s, {CCOUNT} knob sweeps every {PERIOD} s over {len(ccs)} knobs. STEREO, part 1.",
           "suite OCTOPUS", "diag", ""]
    for i, eng in enumerate(ENGINES):
        pats = [p for p in bank if p["engine"].upper() == eng]
        k = used.get(eng, 0)
        used[eng] = k + 1
        p = pats[(3 + 7 * k) % len(pats)]
        rnd = random.Random(1700 + i)
        cyc = f"OCT{i:02d}"
        out.append(f"cycle {cyc} period {PERIOD}")
        for t, ch in CHORDS:
            for n in ch:
                out.append(f"at {t:.2f}  note {n} vel 100 len {LEN}")
        out.extend(MORPH_ROLL)
        for _ in range(CCOUNT):
            t = rnd.uniform(0.0, PERIOD - 0.3)
            out.append(f"at {t:.2f}  knob {rnd.choice(ccs)} {rnd.randint(0, 127)} {rnd.randint(0, 127)} over {rnd.uniform(0.3, 3.0):.2f}")
        out.append("end")
        out.append("")
        out.append(f"test OCT_{eng}{k + 1}  {eng} from #{p['number']:02d} {p['name']}, every knob swept at random while chords play, {secs} s")
        out.append("mode STEREO")
        out.append(f'load patch 1 #{p["number"]:02d} "{p["name"]}"')
        out.append(f"soak {secs} repeat {cyc}")
        out.append("check 60")
        out.append("tail 3")
        out.append("expect report")
        out.append("")
    path = os.path.join(HERE, "bench_suites", "OCTOPUS.txt")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"gen_octopus_suite: OCTOPUS: {len(ENGINES)} tests x {secs} s, {len(ccs)} knobs -> {path}")


if __name__ == "__main__":
    main()
