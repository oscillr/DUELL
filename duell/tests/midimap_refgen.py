"""The reference for tests/midimap_test.c: cloud/base3's midi_control.c and midi_learn.c (tests/midimap_ref_control.c, midimap_ref_learn.c,
byte for byte the files of cloud/base3) with every name they define at file scope put under the prefix ref_ / REF_, so the old and the new
code can live in one test and be fed the same CCs.

  tests/midimap_refgen.py OUTDIR      writes OUTDIR/midimap_ref_control.inc and OUTDIR/midimap_ref_learn.inc

Two lines are changed besides the names, on purpose: the old learn table is a private array of the reference (it was favorites.factory[14],
which holds the settings record's map header now), and nothing else. The names not renamed are the ones the reference shares with the firmware
(the tracks, the MIDI routing, morph_push, mod_midi, mode_apply, the voice and chord code, MQ_PART_ALL which is the same macro)."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONTROL = """midi_channel_t midi_ch midi_sel_on midi_notes midi_owners MIDI_PEDAL_NOTE midi_channel midi_targets midi_expression_1 midi_expression
midi_expression_channel midi_note_held midi_local_held midi_release midi_play midi_note_event midi_pedal_up midi_forget_track
midi_silence_track midi_track_held MCC_CUT MCC_RES MCC_UF MIDI_CC_MAP MIDI_CC_ENG midi_cc_set ML_N ML_E0 ml_ids_fit ml_tab ml_io ml_arm ml_heard
ml_id ml_free_cc midi_learned midi_cc_map midi_morph_fired MIDI_MORPH_CC midi_morph midi_control MIDI_MODE_CC MIDI_BAL_CC MIDI_XF_CC
MIDI_SPLIT_CC midi_mode_cc PCQ_N PCQ_MULTI pcq_buf pcq_w pcq_r midi_pc midi_route_block midi_event""".split()
LEARN = """ML_NOCC ml_code ml_get ml_put ml_cc_of ml_count ml_drop ml_learn ml_clear_all ml_off ml_toggle ml_knob ml_name ml_poll ml_oct ml_line
ml_row_free""".split()


def ren(text, names):
    for n in sorted(set(names), key=len, reverse=True):
        pre = "REF_" if n.isupper() or n.startswith("MIDI_") or n.startswith("ML_") or n.startswith("MCC_") or n.startswith("PCQ_") else "ref_"
        text = re.sub(r"\b" + re.escape(n) + r"\b", pre + n, text)
    return text


def main(out):
    names = CONTROL + LEARN
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    c = (HERE / "midimap_ref_control.c").read_text()
    l = (HERE / "midimap_ref_learn.c").read_text()
    old = "static uint8_t *const ml_tab = favorites.factory[14];"
    if old not in l:
        sys.exit("midimap_refgen: the learn table's line is not in midimap_ref_learn.c")
    l = l.replace(old, "static uint8_t ref_learn_store[32];\nstatic uint8_t *const ml_tab = ref_learn_store;")
    head = "/* generated by tests/midimap_refgen.py from cloud/base3's %s: every file-scope name under ref_ / REF_; do not edit */\n"
    (out / "midimap_ref_control.inc").write_text(head % "midi_control.c" + ren(c, names))
    (out / "midimap_ref_learn.inc").write_text(head % "midi_learn.c" + ren(l, names))
    print("midimap_refgen: %d names -> %s" % (len(set(names)), out))


if __name__ == "__main__":
    main(sys.argv[1])
